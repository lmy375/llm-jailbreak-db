// One-off data migration: packages the upstream promptDatabase (from the
// sibling `ai-jailbreak-cn` repo) plus the supplemental metadata in
// scripts/migrate-map.yaml into the single normalized jailbreak_prompts.yaml used by the site.
//
// It authors no prompt content and improves none — it only re-packages
// already-published research data.
//
// Usage: SRC_SCRIPT=/path/to/script.js node scripts/gen-db.mjs

import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const SRC =
  process.env.SRC_SCRIPT || '/Users/moon/Desktop/code/ai-jailbreak-cn/script.js';
const root = path.resolve(import.meta.dirname, '..');

const map = yaml.load(
  fs.readFileSync(path.join(root, 'scripts', 'migrate-map.yaml'), 'utf8')
);
const methodById = Object.fromEntries(map.jailbreak_method.map((t) => [t.id, t]));
const sourceIdByUrl = Object.fromEntries(map.source.map((s) => [s.url, s.id]));


// ---- extract the upstream promptDatabase -----------------------------------
const text = fs.readFileSync(SRC, 'utf8');
const start = text.indexOf('const promptDatabase = [');
const end = text.indexOf('let activeCategory');
if (start < 0 || end < 0) throw new Error('promptDatabase not found in ' + SRC);
const body = text.slice(start, end);
const upstream = eval(body.slice(0, body.lastIndexOf('];') + 2) + '; promptDatabase');

// ---- YAML serializer --------------------------------------------------------
const dq = (s) => JSON.stringify(String(s ?? ''));
const block = (s, indent) => {
  const text = String(s ?? '').replace(/\r\n?/g, '\n').replace(/\s+$/, '');
  if (!text.includes('\n')) return dq(text);
  const pad = ' '.repeat(indent);
  return '|-\n' + text.split('\n').map((l) => (l ? pad + l : '')).join('\n');
};

const L = [];
L.push('# 越狱提示词 — 主数据文件 / Jailbreak Prompts — main data file');
L.push('# 由 scripts/gen-db.mjs 生成；数据源：scripts/migrate-map.yaml + 上游 promptDatabase。');
L.push('# Generated by scripts/gen-db.mjs. Do not edit by hand if you plan to re-run the migration.');
L.push(`# generated: ${new Date().toISOString().slice(0, 10)}`);
L.push('');

L.push('source:');
for (const s of map.source) {
  L.push(`  - id: ${s.id}`);
  L.push(`    title: ${dq(s.title)}`);
  L.push(`    url: ${dq(s.url)}`);
  L.push(`    index_time: ${dq(s.index_time)}`);
  L.push(`    commit: ${dq(s.commit)}`);
  L.push(`    description: ${dq(s.description)}`);
  L.push(`    description_zh: ${dq(s.description_zh)}`);
}
L.push('');

L.push('models:');
{
  const seen = new Set();
  for (const o of upstream) {
    const m = map.items[o.id];
    if (m && !seen.has(m.model)) seen.add(m.model);
  }
  for (const o of upstream) {
    const m = map.items[o.id];
    if (!m || !seen.has(m.model)) continue;
    seen.delete(m.model);
    L.push(`  - id: ${m.model}`);
    L.push(`    name: ${dq(m.model_name)}`);
  }
}
L.push('');

L.push('jailbreak_method:');
for (const t of map.jailbreak_method) {
  L.push(`  - id: ${t.id}`);
  L.push(`    name: ${dq(t.name)}`);
  L.push(`    name_zh: ${dq(t.name_zh)}`);
}
L.push('');

L.push('target:');
for (const t of map.target) {
  L.push(`  - id: ${t.id}`);
  L.push(`    name: ${dq(t.name)}`);
  L.push(`    name_zh: ${dq(t.name_zh)}`);
}
L.push('');

L.push('prompts:');
// id must be LJB-<year>-<seq>: the year comes from the entry's `time`; when the
// time is unknown, a clue timestamp (the source repo commit date, or the source
// page / its metadata date) is used as the year — never LJB-XXXX.
// The sequence is always 4 digits, zero-padded (e.g. LJB-2025-0001).
const seqByYear = {};
upstream.forEach((o, i) => {
  const m = map.items[o.id];
  if (!m) throw new Error('missing migration mapping for upstream id: ' + o.id);
  const t = methodById[m.jailbreak_method];
  if (!t) throw new Error('unknown jailbreak_method: ' + m.jailbreak_method);

  // Year: from `time`; when the time is unknown, fall back to a clue timestamp
  // (the source entry's index_time, or a year in the source URL). No LJB-XXXX.
  let year = /^\d{4}/.test(String(m.time)) ? String(m.time).slice(0, 4) : '';
  if (!year) {
    const src = map.source.find((s) => s.id === sourceIdByUrl[m.source]);
    const ym = /(20\d{2})/.exec(String(src?.index_time ?? m.source ?? ''));
    if (ym) year = ym[1];
  }
  if (!year) {
    throw new Error(
      `no year for upstream id ${o.id}: supply time or a clue year in the source entry`
    );
  }
  seqByYear[year] = (seqByYear[year] ?? 0) + 1;
  const id = `LJB-${year}-${String(seqByYear[year]).padStart(4, '0')}`;
  const sourceId = sourceIdByUrl[m.source];
  if (!sourceId) throw new Error('no top-level source entry for url: ' + m.source);

  // Upstream `proofs` links fold into bilingual note / note_zh as plain text.
  const noteEn = [];
  const noteZh = [];
  if (Array.isArray(o.proofs) && o.proofs.length) {
    noteEn.push(`Proofs: ${o.proofs.join(' ; ')}`);
    noteZh.push(`证据：${o.proofs.join(' ；')}`);
  }

  L.push(`  - id: ${id}`);
  L.push(`    title: ${dq(m.title)}`);
  L.push(`    title_zh: ${dq(o.title)}`);
  L.push(`    model_id: ${dq(m.model)}`);
  L.push(`    time: ${dq(m.time)}`);
  L.push(`    source_id: ${sourceId}`);
  L.push(`    source_url: ${dq(m.source)}`);
  L.push(`    jailbreak_method: ${m.jailbreak_method}`);
  L.push(`    target: ${map.item_target?.[o.id] ?? 'dan'}`);
  L.push(`    prompt: ${block(o.original, 6)}`);
  L.push(`    prompt_zh: ${block(o.content, 6)}`);
  if (noteEn.length) {
    L.push(`    note: ${dq(noteEn.join('. '))}`);
    L.push(`    note_zh: ${dq(noteZh.join('。'))}`);
  }
});

fs.writeFileSync(path.join(root, 'jailbreak_prompts.yaml'), L.join('\n') + '\n');
console.log(`jailbreak_prompts.yaml written: ${map.jailbreak_method.length} methods, ${upstream.length} prompts`);